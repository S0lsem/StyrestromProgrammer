def _app_icon_path() -> Optional[Path]:
    """Locate the bundled icon.ico (PyInstaller _MEIPASS when frozen, else the
    source folder). Returns None if it isn't present."""
    if getattr(sys, 'frozen', False):
        base = Path(getattr(sys, '_MEIPASS', Path(sys.executable).parent))
    else:
        base = Path(__file__).parent
    p = base / 'icon.ico'
    return p if p.exists() else None


def main() -> None:
    # Before anything Qt: an exception escaping a slot makes PyQt6 abort the
    # process, and with console=False that traceback goes to a dead stderr.
    # This turns those silent deaths into ~/.mrs_programmer/logs/crash.log.
    crashlog.install()

    app = QApplication(sys.argv)
    app.setStyle('Fusion')
    _icon = _app_icon_path()
    if _icon:
        app.setWindowIcon(QIcon(str(_icon)))
    win = MainWindow()
    if not win._login_ok:
        # Operator cancelled the login gate — nothing to show.
        return
    win.show()
    sys.exit(app.exec())


if __name__ == '__main__':
    main()
