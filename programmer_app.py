def _ago(unix_seconds: int) -> str:
    """'12 minute(s) ago' — deliberately vague; the exact second never matters."""
    import time as _time
    if not unix_seconds:
        return 'never'
    seconds = max(0, int(_time.time()) - int(unix_seconds))
    if seconds < 90:
        return 'just now'
    minutes = seconds // 60
    if minutes < 90:
        return f'{minutes} minute(s) ago'
    hours = minutes // 60
    if hours < 48:
        return f'{hours} hour(s) ago'
    return f'{hours // 24} day(s) ago'


def _matches_any(part: str, patterns) -> bool:
    """Client-side twin of the server's allow-list match, so the ticked boxes
    show exactly what the proxy would let through."""
    name = str(part).strip().lower()
    return any(fnmatch.fnmatchcase(name, str(p).strip().lower()) for p in patterns)


