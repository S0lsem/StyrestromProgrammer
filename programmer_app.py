    @crashlog.guard
    def _on_trace_frame(self, direction: str, arb_id: int, data: bytes) -> None:
        if not self._trace_record.isChecked():
            return
        import time
        now = time.monotonic()
        if self._trace_t0 is None:
            self._trace_t0 = now
        t_ms = (now - self._trace_t0) * 1000.0

        self._trace_frames.append((t_ms, direction, arb_id, bytes(data)))
        hexb = ' '.join(f'{b:02X}' for b in data)
        self._trace_edit.appendPlainText(
            f'{len(self._trace_frames):>4}  {t_ms:>9.1f}  {direction:<2}  '
            f'{arb_id:08X}  {len(data)}  {hexb}'
        )

    def _clear_trace(self) -> None:
        self._trace_frames.clear()
        self._trace_t0 = None
        self._trace_edit.clear()

    def _save_trace(self) -> None:
        if not self._trace_frames:
            QMessageBox.information(self, 'CAN trace', 'No frames captured yet.')
            return
        path, _ = QFileDialog.getSaveFileName(
            self, 'Save CAN trace', 'can_trace.trc', 'PEAK trace (*.trc)'
        )
        if not path:
            return
        try:
            _write_trc(Path(path), self._trace_frames)
            self._append_log(f'CAN trace saved to {path}')
        except OSError as exc:
            QMessageBox.warning(self, 'CAN trace', f'Could not save: {exc}')

