    def _on_module_changed(self, _index: int) -> None:
        """Re-arm the batch listener on the newly selected module's bus."""
        # May fire while the UI is still being built, before _batch_check exists.
        check = getattr(self, '_batch_check', None)
        if check is None or not check.isChecked():
            return
        self._stop_batch_listener()
        self._maybe_start_batch_listener()

    def _on_batch_toggled(self, _state: int) -> None:
        if self._batch_check.isChecked():
            self._maybe_start_batch_listener()
        else:
            self._stop_batch_listener()
            if not (self._flash_thread and self._flash_thread.isRunning()):
                self._status_label.setText('Ready')

    def _maybe_start_batch_listener(self) -> None:
        """Start the listener if all preconditions hold; no-op otherwise."""
        if not self._batch_check.isChecked():
            return
        if self._firmware is None:
            return
        if not self._detected_channel:
            return
        if self._thread_is_running(self._flash_thread):
            return
        if self._thread_is_running(self._batch_thread):
            return
        self._start_batch_listener()

    @staticmethod
    def _thread_is_running(thread) -> bool:
        """Safe isRunning() — the QThread may have been deleteLater-ed,
        in which case touching it raises RuntimeError from sip."""
        if thread is None:
            return False
        try:
            return thread.isRunning()
        except RuntimeError:
            return False

    def _start_batch_listener(self) -> None:
        # Listen on the bus the selected module actually talks on. A CAN FD
        # module never appears on a 125k classical bus, so a fixed 125k
        # listener would wait forever and batch mode would never fire.
        cfg = MODULE_TYPES[self._module_combo.currentText()]
        self._batch_listener = BatchListenerWorker(
            self._detected_channel,
            bitrate=cfg['bitrate'],
            is_can_fd=cfg['can_fd'],
            data_bitrate=cfg['data_bitrate'],
        )
        self._batch_thread = QThread(self)
        self._batch_listener.moveToThread(self._batch_thread)

        self._batch_thread.started.connect(self._batch_listener.run)
        self._batch_listener.plc_detected.connect(self._on_batch_plc_detected)
        self._batch_listener.frame.connect(self._on_trace_frame)
        self._batch_listener.error.connect(self._on_batch_listener_error)
        self._batch_listener.plc_detected.connect(self._batch_thread.quit)
        self._batch_listener.error.connect(self._batch_thread.quit)
        # Qt-managed cleanup. Order matters: our ref-clear slot fires first
        # (drops Python refs while wrappers are still valid), then deleteLater
        # schedules C++ destruction. Without explicit deleteLater the Python
        # GC can race the Qt event loop and crash on pending signal slots.
        self._batch_thread.finished.connect(self._on_batch_thread_finished)
        self._batch_thread.finished.connect(self._batch_listener.deleteLater)
        self._batch_thread.finished.connect(self._batch_thread.deleteLater)

        self._batch_thread.start()
        baud = describe_baud(cfg['bitrate'], cfg['can_fd'], cfg['data_bitrate'])
        self._status_label.setText(f'Batch mode — waiting for next PLC ({baud})…')
        self._append_log(
            f'Batch mode: listening at {baud} for the next PLC boot announcement. '
            f'Power-cycle the next module to start its flash.'
        )

    @crashlog.guard
    def _on_batch_thread_finished(self) -> None:
        """Drop Python refs once the thread has fully exited.

        This is only safe because the QThread is parented to the window, so
        Qt owns the C++ object and dropping our reference cannot destroy it.
        Unparented, the wrapper owned it, and clearing the ref here killed
        the app outright — ``finished`` is emitted while the thread is still
        winding down, so the GC would delete a *running* QThread and Qt
        answers that with qFatal(). Recorded 2026-08-31 19:59:23 as
        "QThread: Destroyed while thread '' is still running", from this slot.
        """
        self._batch_listener = None
        self._batch_thread = None

    def _stop_batch_listener(self) -> None:
        if self._batch_listener is None:
            return
        self._batch_listener.request_stop()
        if self._thread_is_running(self._batch_thread):
            try:
                self._batch_thread.quit()
                self._batch_thread.wait(2000)
            except RuntimeError:
                pass
        self._batch_listener = None
        self._batch_thread = None

    @crashlog.guard
    def _on_batch_plc_detected(self, serial: int) -> None:
        # Ref cleanup happens via _on_batch_thread_finished — touching the
        # worker/thread refs here while signals are still in flight crashes
        # Qt.
        self._append_log(f'Auto-detected PLC SN {serial} on boot — starting flash.')
        self._on_flash()

    @crashlog.guard
    def _on_batch_listener_error(self, msg: str) -> None:
        self._append_log(f'Batch listener stopped: {msg}')
        self._status_label.setText('Batch listener error — see log.')

    def closeEvent(self, event) -> None:   # noqa: N802 — Qt method name
        self._stop_batch_listener()
        self._drain_threads()
        self._wait_for_event_posts()
        self._detach_log_handler()
        super().closeEvent(event)

    def _detach_log_handler(self) -> None:
        """Take the GUI log handler off the root logger before the window goes.

        ``_QLogHandler`` is a QObject as well as a logging.Handler. Left
        attached, Python's ``logging.shutdown()`` atexit hook reaches for it
        after Qt has destroyed the C++ side and raises "wrapped C/C++ object
        has been deleted". Harmless at that point in the shutdown, but it is a
        dangling reference to a dead object and there is no reason to keep one.
        """
        handler = getattr(self, '_log_handler', None)
        if handler is None:
            return
        try:
            logging.getLogger().removeHandler(handler)
        except Exception:   # noqa: BLE001 — never obstruct a close
            pass
        self._log_handler = None

    def _drain_threads(self, timeout_ms: int = 5000) -> None:
        """Stop the worker threads before the window that owns them is destroyed.

        Qt destroys child objects along with their parent, and destroying a
        *running* QThread is a fatal — the crash recorded on 2026-08-31. So
        every thread gets asked to stop first.

        A scan cannot be cancelled (``scan_plc`` blocks with no stop flag), so
        one may still be running when the timeout expires. Such a thread is
        disowned rather than destroyed: leaking a thread in a process that is
        exiting anyway costs nothing, and aborting the app in front of the
        operator costs a great deal.
        """
        if self._flash_worker is not None:
            try:
                self._flash_worker.cancel()
            except RuntimeError:
                pass   # already deleted by Qt — nothing to cancel

        for thread in (self._flash_thread, self._scan_thread, self._dl_thread):
            if not self._thread_is_running(thread):
                continue
            try:
                thread.quit()
                if not thread.wait(timeout_ms):
                    thread.setParent(None)
                    self._abandoned.append(thread)
            except RuntimeError:
                pass

    @crashlog.guard
    def _on_flash_thread_finished(self) -> None:
        """Drop Python refs once the flash thread has fully exited.
        Mirrors _on_batch_thread_finished — without it, ~20 rapid batch
        flashes accumulate stale wrapper state and eventually crash Qt.

        This is also where batch mode resumes. The listener needs exclusive
        PCAN access, so _maybe_start_batch_listener() refuses to start while
        the flash thread is still running. _on_flash_done() runs too early
        for that — it fires before _flash_thread.quit() is processed, so the
        guard sees the thread still alive and bails. (That's why batch
        auto-flash used to work exactly once: the first flash's completion
        popup pumped a nested event loop that let the thread finish before
        the restart, accidentally masking the bug.) Restarting here — after
        the thread has genuinely exited and refs are cleared — is reliable."""
        self._flash_worker = None
        self._flash_thread = None
        self._maybe_start_batch_listener()

    def _on_flash(self) -> None:
        # While a flash/reflash loop is running, this button acts as Stop.
        if self._flashing:
            if self._flash_worker is not None:
                self._flash_worker.cancel()
            self._flash_btn.setEnabled(False)
            self._status_label.setText('Stopping…')
            self._append_log('Stop requested — finishing current attempt…')
            return

        if self._firmware is None:
            QMessageBox.warning(
                self, 'No firmware',
                'Pick a part and click Download before flashing.',
            )
            return

        if not self._detected_channel:
            QMessageBox.warning(
                self, 'No adapter',
                'No PCAN adapter detected.\n\nClick "Detect adapter" first.',
            )
            return

        # If the batch listener is running, stop it — the flasher needs
        # exclusive PCAN access. We'll restart it after this flash completes.
        self._stop_batch_listener()

        module_name  = self._module_combo.currentText()
        channel      = self._detected_channel
        firmware     = self._firmware
        cfg          = MODULE_TYPES[module_name]

        # All flashing goes through the newer .NET flasher. The classical
        # console (V1.41.10) can't read the current MRS firmware format at all
        # ("No data found"), and can't reach a module running at its app baud.
        # The .NET flasher reads the firmware and speaks every baud; the module
        # dropdown picks it: 125k (blank/bootloader), 500k (programmed
        # classical), or 500k:2000k (CAN FD). --restart-module drops a running
        # module into the bootloader so it's caught at its app baud.
        net_baud = describe_baud(cfg['bitrate'], cfg['can_fd'], cfg['data_bitrate'])
        retries = 4

        self._last_plc_info = None
        self._flashing = True
        self._flash_prev_btn_text = self._flash_btn.text()
        self._flash_btn.setText('■ Stop')     # stays enabled so the loop is cancellable
        self._download_btn.setEnabled(False)
        self._progress_bar.setValue(0)
        self._status_label.setText('Starter flasher…')
        self._append_log(f'Starting flash — module: {module_name}  channel: {channel}')
        self._append_log(
            f'Flashing at {net_baud} (restart-module). Programmed module: keep '
            'it powered. Blank module: power-cycle to catch the boot. Stop to abort.'
        )

        self._flash_worker = FlashWorker(firmware, retries=retries, net_baud=net_baud)
        self._flash_thread = QThread(self)
        self._flash_worker.moveToThread(self._flash_thread)

        self._flash_thread.started.connect(self._flash_worker.run)
        self._flash_worker.progress.connect(self._on_progress)
        self._flash_worker.plc_found.connect(self._on_plc_found)
        self._flash_worker.finished.connect(self._on_flash_done)
        self._flash_worker.error.connect(self._on_flash_error)
        self._flash_worker.cancelled.connect(self._on_flash_cancelled)
        self._flash_worker.finished.connect(self._flash_thread.quit)
        self._flash_worker.error.connect(self._flash_thread.quit)
        self._flash_worker.cancelled.connect(self._flash_thread.quit)
        # Qt-managed cleanup so batch programming doesn't race the Python
        # GC after ~20 rapid flashes. Same pattern as BatchListenerWorker:
        # clear Python refs first (so any subsequent isRunning() check on
        # them harmlessly returns False), then deleteLater the C++ objects.
        self._flash_thread.finished.connect(self._on_flash_thread_finished)
        self._flash_thread.finished.connect(self._flash_worker.deleteLater)
        self._flash_thread.finished.connect(self._flash_thread.deleteLater)

        self._flash_thread.start()

