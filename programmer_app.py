# Scan worker — listens for a PLC boot announcement and reads identity
# ---------------------------------------------------------------------------

class ScanWorker(QObject):
    result  = pyqtSignal(object)   # PLCInfo
    partial = pyqtSignal(int, str) # (serial, friendly message) — detected, identity unreadable (CAN FD)
    error   = pyqtSignal(str)
    frame   = pyqtSignal(str, int, bytes)  # (direction, arb_id, data) for the trace

    def __init__(
        self,
        channel:      str,
        bitrate:      int,
        is_can_fd:    bool,
        data_bitrate: int,
    ) -> None:
        super().__init__()
        self._channel      = channel
        self._bitrate      = bitrate
        self._is_can_fd    = is_can_fd
        self._data_bitrate = data_bitrate

    def run(self) -> None:
        try:
            info = scan_plc(
                self._channel, self._bitrate, self._is_can_fd, self._data_bitrate,
                on_frame=lambda d, i, data: self.frame.emit(d, i, data),
            )
            self.result.emit(info)
        except PartialScanError as exc:
            self.partial.emit(exc.serial, str(exc))
        except ScanError as exc:
            self.error.emit(str(exc))
        except Exception as exc:
            self.error.emit(
                ''.join(traceback.format_exception(type(exc), exc, exc.__traceback__))
            )


# ---------------------------------------------------------------------------
# Batch listener — between flashes in batch mode, watches for the next PLC's
# boot announcement so the GUI can auto-trigger the next flash. The bus is
# released as soon as the announcement is seen because the console flasher
# needs exclusive PCAN access.
#
# The listener MUST sit on the same bus the module talks on, which is the baud
# from the module dropdown — not a fixed 125k. Only a blank module stays in the
# 125k bootloader; a programmed one announces at its app baud (500k classical,
# or 500k:2000k CAN FD) and then runs its firmware. Listening at 125k to a
# CAN FD module hears nothing at all, which is why batch mode never
# auto-triggered for CAN FD and every unit had to be flashed by hand.
# ---------------------------------------------------------------------------

class BatchListenerWorker(QObject):
    plc_detected = pyqtSignal(int)   # serial decoded from boot announcement
    error        = pyqtSignal(str)
    frame        = pyqtSignal(str, int, bytes)  # (direction, arb_id, data) for the trace

    def __init__(self, channel: str, bitrate: int = 125000,
                 is_can_fd: bool = False, data_bitrate: int = 0) -> None:
        super().__init__()
        self._channel      = channel
        self._bitrate      = bitrate
        self._is_can_fd    = is_can_fd
        self._data_bitrate = data_bitrate
        self._stop = False

    def request_stop(self) -> None:
        self._stop = True

    def run(self) -> None:
        from mrs_protocol.protocol import CAN_ID_PLC_BOOT, open_pcan
        # Same open as detect_adapter()/scan_plc so a bus that Detect could
        # open is a bus the listener can open.
        try:
            bus = open_pcan(self._channel, self._bitrate,
                            self._is_can_fd, self._data_bitrate)
        except Exception as exc:
            self.error.emit(
                f'Batch listener could not open PCAN at '
                f'{describe_baud(self._bitrate, self._is_can_fd, self._data_bitrate)}: {exc}'
            )
            return

        serial = 0
        try:
            while not self._stop:
                msg = bus.recv(timeout=0.5)
                if msg is None:
                    continue
                data = bytes(msg.data)
                self.frame.emit('Rx', msg.arbitration_id, data)
                if msg.arbitration_id == CAN_ID_PLC_BOOT and len(msg.data) >= 5:
                    serial = (data[2] << 16) | (data[3] << 8) | data[4]
                    break
        finally:
            try:
                bus.shutdown()
            except Exception:
                pass

        if not self._stop:
            self.plc_detected.emit(serial)


# ---------------------------------------------------------------------------
# Event reporter — posts flash events to HQ in a QThread
# ---------------------------------------------------------------------------

class _EventPostWorker(QObject):
    """POST one flash event (or drain the offline queue) off the GUI thread.

    ``report_event`` does a blocking ``urlopen`` with a 15 s timeout, and on
    success it drains the pending queue too — one more blocking POST per
    queued event. Called straight from a slot, as it used to be, that is a
    multi-second freeze after every single flash; a queue built up during an
    offline shift turns the next flash into a minutes-long hang, which Windows
    files as AppHangB1 and the operator files as "it crashed".
    """
    done = pyqtSignal(str)   # one line for the log panel ('' = say nothing)

    def __init__(self, event: Optional[dict]) -> None:
        super().__init__()
        self._event = event

    def run(self) -> None:
        try:
            if self._event is None:
                sent = event_logger.replay_pending()
                self.done.emit(
                    f'Replayed {sent} queued flash event(s) to HQ.' if sent else ''
                )
                return

            response = event_logger.report_event(self._event)
            if response is None:
                self.done.emit(
                    'Event queued offline (proxy unreachable); '
                    'will retry on next launch.'
                )
                return

            tag = (
                'FIRST-TIME PROGRAM'
                if response.get('first_program_for_sn') else
                'reflash'
            )
            self.done.emit(
                f'Event reported to HQ ({tag}) by '
                f'{self._event["operator"]} @ {self._event["distributor"]}.'
            )
        except Exception as exc:   # noqa: BLE001 — reporting must never kill a flash
            self.done.emit(f'Event reporting failed (flash itself was fine): {exc}')


# ---------------------------------------------------------------------------
# Flash worker — runs the CAN flash sequence in a QThread
# ---------------------------------------------------------------------------

# How many scan passes the flasher makes before giving up. A blank module is
# caught on pass 1; a programmed module only sits in the bootloader for a few
# ms per power-up, so reflashing it needs many passes while the operator
# repeatedly power-cycles it. The operator can Stop early at any time.
REFLASH_RETRIES = 40


class FlashWorker(QObject):
    progress   = pyqtSignal(float, str)
    plc_found  = pyqtSignal(object)   # SimpleNamespace(serial=str, label=str)
    finished   = pyqtSignal()
    error      = pyqtSignal(str)
    cancelled  = pyqtSignal()

    def __init__(self, firmware: Firmware, retries: int = 1,
                 net_baud: Optional[str] = None) -> None:
        super().__init__()
        self._firmware = firmware
        self._retries  = retries
        self._net_baud = net_baud
        self._cancel   = False

    def cancel(self) -> None:
        self._cancel = True

    def run(self) -> None:
        try:
            def _on_plc(sn: str, label: str) -> None:
                self.plc_found.emit(SimpleNamespace(serial=sn, label=label))

            result = run_flash(
                self._firmware,
                progress=self.progress.emit,
                plc_found=_on_plc,
                cancel_check=lambda: self._cancel,
                retries=self._retries,
                net_baud=self._net_baud,
            )

            if self._cancel:
                self.cancelled.emit()
                return
            if result.success:
                self.finished.emit()
                return

            detail = result.error_message or f'exit code {result.exit_code}'
            if result.error_code:
                detail = f'0x{result.error_code:02X} ({result.error_code}): {detail}'
            self.error.emit(
                f'Console flasher reported failure: {detail}\n\n'
                f'--- flasher output ---\n{result.output}'
            )
        except Exception as exc:
            self.error.emit(
                ''.join(traceback.format_exception(type(exc), exc, exc.__traceback__))
            )


